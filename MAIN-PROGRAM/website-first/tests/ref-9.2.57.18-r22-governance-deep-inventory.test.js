const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.join(__dirname,'..');
const inv=JSON.parse(fs.readFileSync(path.join(ROOT,'config/governed-gate-inventory-v30.json'),'utf8'));
const ai=JSON.parse(fs.readFileSync(path.join(ROOT,'config/ai-operational-inventory-v30.json'),'utf8'));
const parity=JSON.parse(fs.readFileSync(path.join(ROOT,'config/environment-parity-v30.json'),'utf8'));
const reg=JSON.parse(fs.readFileSync(path.join(ROOT,'config/service-registry-v30.json'),'utf8'));
const slots=JSON.parse(fs.readFileSync(path.join(ROOT,'config/external-provider-slots-v30.json'),'utf8')).slots;
const firewall=require('../../backend/src/services/external-gate-firewall');
test('R22 deep governance inventory has no service/gate double-binding and all 31 AIs are wired',()=>{
 assert.equal(ai.internalAICount,31); assert.equal(ai.ais.length,31);
 assert.equal(new Set(ai.ais.map(x=>x.aiId)).size,31);
 assert.equal(new Set(ai.ais.map(x=>x.internalGate)).size,31);
 assert.ok(ai.ais.every(x=>x.handlerDeclared));
 assert.equal(inv.counts.totalGovernedGateRecords,103);
 assert.equal(inv.providerServiceClasses.length,24);
 assert.equal(slots.length,72);
 assert.equal(new Set(slots.map(x=>x.service)).size,24);
 assert.ok(inv.providerAlternateGates.every(x=>x.service && x.providerSlotId));
 assert.ok(inv.nonAiPrimaryGates.every(x=>x.service && x.gate));
 assert.ok(inv.nonAiPrimaryGates.every(x=>x.internalLayer==='always_on' && x.externalLayer==='master_admin_controlled'));
 assert.ok(inv.providerAlternateGates.every(x=>x.internalLayer==='always_on' && x.externalLayer==='master_admin_controlled' && x.firewallRequired===true));
 assert.ok(inv.projectMemoryGovernanceGates.every(x=>x.internalLayer==='always_on' && x.externalLayer==='master_admin_controlled' && x.firewallRequired===true));
 assert.equal(Object.keys(reg.services).length,24);
 for(const x of slots) assert.ok(x.service in reg.services);
 assert.ok(parity.development.sourceContract==='same' && parity.production.sourceContract==='same');
 assert.equal(firewall.status().totalGovernedGateRecords,103); assert.equal(firewall.status().providerServiceClassCount,24);
});
console.log('PASS R22 deep inventory: 31/31 AIs, 24 service classes, 72 alternates, 3 memory gates, no mixed-service gate records, dev/prod source contract parity');
