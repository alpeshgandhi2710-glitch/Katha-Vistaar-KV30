'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const cfg=JSON.parse(fs.readFileSync(path.join(root,'config/payment-recovery-protocol-v30.json'),'utf8'));
const m=require(path.join(root,'services/payment-settlement-manager.js'));
assert.equal(cfg.version,'REF-8.3.155.9.2.21');
assert.equal(cfg.rules.externalRecoveryMustUseDedicatedAuthoritativeReconciliationBoundary,true);
assert.equal(cfg.adminRecovery.reconcileEndpoint,'/api/admin/payment-recoveries/:recoveryId/reconcile');
const a=m.createRecovery({direction:'user_to_katha_vistaar',referenceId:'REC-BOUNDARY-1',transactionId:'TX-BOUNDARY-1'});
const b=m.createRecovery({direction:'user_to_katha_vistaar',referenceId:'REC-BOUNDARY-1',transactionId:'TX-BOUNDARY-1'});
assert.equal(a.id,b.id);
a.recoveryState='recovery_failed';
const c=m.createRecovery({direction:'user_to_katha_vistaar',referenceId:'REC-BOUNDARY-1',transactionId:'TX-BOUNDARY-1'});
assert.equal(c.id,a.id);
assert.equal(m.classifyProviderResult({status:'accepted',debited:true}).state,'reconciliation_required');
assert.equal(m.classifyProviderResult({status:'settled',debited:true}).state,'settled');
const src=fs.readFileSync(path.join(root,'src/server.js'),'utf8');
assert.match(src,/external_payment_reconciliation/);
assert.match(src,/action:'reconcile'/);
assert.ok(src.includes("idempotencyKey:`reconcile:${transactionId||recovery.transactionId||recovery.referenceId}`"));
console.log('REF-8.3.155.9.2.21 payment recovery boundary PASS');
