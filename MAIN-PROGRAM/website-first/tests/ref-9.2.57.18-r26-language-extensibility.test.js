'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const websiteRoot=path.resolve(__dirname,'..');
const langCfg=JSON.parse(fs.readFileSync(path.join(websiteRoot,'config','languages.json'),'utf8'));
const arch=JSON.parse(fs.readFileSync(path.join(websiteRoot,'config','language-architecture-v30.json'),'utf8'));
const runtime=JSON.parse(fs.readFileSync(path.join(websiteRoot,'config','language-runtime-governance-v30.json'),'utf8'));
const app=fs.readFileSync(path.join(websiteRoot,'public','app.js'),'utf8');
const server=fs.readFileSync(path.join(websiteRoot,'src','server.js'),'utf8');

assert.equal(langCfg.indianLanguageCount,22);
assert.equal(langCfg.canonicalLanguageCount,23);
assert.equal(langCfg.futureLanguagesAllowed,true);
assert.equal(langCfg.fallbackLanguageCode,'en');
assert.match(langCfg.fallbackPolicy,/ENGLISH_CATALOG_FALLBACK_FOR_MISSING_EMPTY_PLACEHOLDER_OR_UNAVAILABLE_VALUES/);
assert.equal(arch.futureLanguagesAllowed,true);
assert.equal(arch.noHardcodedUserFacingText,true);
assert.equal(runtime.futureLanguagesAllowed,true);
assert.match(runtime.fallbackRule,/missing, empty, whitespace-only, or explicit \[key\] values fall back to the authoritative English catalog/);
assert.match(app,/function localeValue\(lang,key\)/);
assert.match(app,/if\(!enabled\)return localeValue\('en',key\)\?\?key;/);
assert.match(app,/if\(v==null\|\|String\(v\)\.trim\(\)===''\|\|String\(v\)\.trim\(\)===`\[\$\{key\}\]`\)v=localeValue\('en',key\);/);
assert.match(app,/\/locales\/\$\{encodeURIComponent\(row\.code\)\}\.json/);
assert.match(app,/await loadLocaleBundles\(\);/);
assert.match(server,/futureLanguagesAllowed:true/);
assert.match(server,/bundlePath:x\.code==='en'\?null:`\/locales\/\$\{encodeURIComponent\(x\.code\)\}\.json`/);
assert.doesNotMatch(app,/23 separately supported languages\./);
assert.doesNotMatch(app,/\$\{kvIcon\('globe'\)\} 23 languages/);
console.log('R26 language architecture/extensibility: PASS');
