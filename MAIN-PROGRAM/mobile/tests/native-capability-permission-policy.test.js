const fs=require('fs'), path=require('path'), assert=require('assert');
const root=path.join(__dirname,'..');
const native=fs.readFileSync(path.join(root,'lib','native_capabilities.dart'),'utf8');
const policy=fs.readFileSync(path.join(root,'native-config','PERMISSION-POLICY.md'),'utf8');
const android=fs.readFileSync(path.join(root,'native-config','android','permissions.xml'),'utf8');
const ios=fs.readFileSync(path.join(root,'native-config','ios','Info.plist.permission-usage.xml'),'utf8');
const androidHost=fs.readFileSync(path.join(root,'android/app/src/main/kotlin/com/kathavistaar/kv30/MainActivity.kt'),'utf8');
assert(native.includes('class KvPermissionPolicy'));
for(const p of ['notifications','camera','microphone','photos','files','location','nearbyDevices','contacts','calendar','phone','sms','biometric']) assert(native.includes(`KvPermission.${p}`),p);
assert(native.includes('KvFmRecorderController'));
for(const fn of ['start()','pause()','resume()','stop(','trim(']) assert(native.includes(fn),fn);
assert(android.includes('android.permission.INTERNET'));
assert(android.includes('android.permission.RECORD_AUDIO'));
assert(android.includes('android.permission.CAMERA'));
assert(ios.includes('NSMicrophoneUsageDescription'));
assert(ios.includes('NSCameraUsageDescription'));
assert(policy.includes('OFF until the user invokes the feature'));
assert(androidHost.includes('pendingPermissionResult'));
assert(androidHost.includes('onRequestPermissionsResult'));
assert(androidHost.includes('pendingPermissionResult?.success(granted)'));
console.log('native-capability-permission-policy: PASS');
